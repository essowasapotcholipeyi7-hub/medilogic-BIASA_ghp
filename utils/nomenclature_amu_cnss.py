def _extraire_code(nom_acte):
    """Premier mot du nom de l'acte, ex. "S100 Consultation..." -> "S100"
    (meme convention que utils/categorisation.py:extraire_code_acte, mais
    sans se limiter a un jeu de regex fixe puisque le dictionnaire
    ci-dessus couvre deja les codes valides)."""
    if not nom_acte:
        return None
    mots = str(nom_acte).strip().split()
    if not mots:
        return None
    return re.sub(r"[^A-Z0-9]", "", mots[0].upper())


def deviner_categorie_par_code(nom_acte):
    """Categorie CNSS suggeree a partir du code en tete du nom de l'acte,
    ou None si le code est absent/inconnu de la nomenclature."""
    code = _extraire_code(nom_acte)
    if not code:
        return None
    return CODE_VERS_CATEGORIE_CNSS.get(code)
